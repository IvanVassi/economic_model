def snapshot(s) -> dict:
    V = s.value
    gdp = V(155)
    d = dict(t=s.t, gdp=gdp, prod=V(156), unemp=kz.unemployment(s), cpi=V(210), cpi_nom=V(14018), defl=V(14004), infl=kz.inflation(s) if s.t > 1 else 100 * V(14016), rate=V(501),
             living=V(151), quality=V(380), tension=V(152), rev=V(42), exp=V(51), deficit=V(44), acc_def=V(43),
             exports_usd=sum(V(k * 1000 + 169) for k in SEC), imports=sum(V(k * 1000 + 6) for k in SEC),
             reserves=V(524), minfin_usd=V(100), pop=V(17670), vat14=s.lever(14), vat19=s.lever(19), lever122=s.lever(122),
             labour=sum(s.lever(k * 1000 + 12) for k in SEC), unemployed=V(231), n_pens=V(15311), n_pub=V(15111), n_mil=V(15211), n_unemp_grp=V(15411))
    d['comp'] = {c: COEF[c] * V(c) for c in TARGET}                      # вклад в #42, ед. модели
    d['sec'] = {k: dict(out=V(k * 1000 + 1), price=V(k * 1000 + 39), va=V(k * 1000 + 43), unemp=V(k * 1000 + 30),
                        rev=V(k * 1000 + 42), exp_usd=V(k * 1000 + 169), vat=V(k * 1000 + 47)) for k in SEC}
    d['grp'] = {}
    for g in GROUPS:
        if g >= 15000:   # непроизводственные группы: доход +2, уровень жизни +38, напряжённость +85
            d['grp'][g] = dict(income=V(g + 2), living=V(g + 38), tension=V(g + 85), n=V(g + 11))
        else:            # группы работников секторов: k802 / k838 / k885
            b = g * 1000
            d['grp'][g] = dict(income=V(b + 802), living=V(b + 838), tension=V(b + 885), n=V(b + 811))
    return d


def run_scenario(base, levers: dict[int, float], exp_mult: float = 1.0) -> list[dict]:
    s = copy.deepcopy(base)
    kz.background_path(s, kz.INFL_TARGET, kz.INFL_LONGRUN)      # фон инфляции снижается к цели НБК за 2 года
    for k, v in levers.items():
        s.set_lever(k, v)
    if exp_mult != 1.0:
        kz.apply_expenditures(s, s.lever(90) * exp_mult)
    out = [snapshot(s)]
    for _ in range(YEARS):
        s.run(1.0)
        out.append(snapshot(s))
    return out


def main():
    base = calibrate(verbose=False)
    b0 = snapshot(base)
    SCALE = KZ['gdp_trln'] / b0['gdp']                                   # трлн тенге на единицу модели
    USD = (KZ['exports_goods_usd'] + KZ['exports_services_usd']) / b0['exports_usd']   # млрд $ на модельный $
    l122 = base.lever(122)
    nf_cut = (TARGET[41] - 1.5 + 1.5 * 2.8 / 5.25) / TARGET[41]      # таможня 1.5 % ВВП неизменна, трансферт 3.0→1.6
    SCEN = {
        'base': ('Базовый: НДС 12 % (без реформы)', {}, 1.0),
        'A': ('А: НДС 16 % везде', {14: 16, 19: 16}, 1.0),
        'B': ('Б: НДС 16 % в производстве, розничный НДС на продовольствие/ТНП 12 % (льготы)', {14: 16, 19: 12}, 1.0),
        'C': ('В: НДС 16 % + сокращение трансферта Нацфонда (5.25 → 2.8 трлн)', {14: 16, 19: 16, 122: l122 * nf_cut}, 1.0),
    }
    res = {k: run_scenario(base, lev, m) for k, (title, lev, m) in SCEN.items()}
    os.makedirs(os.path.join(ROOT, 'docs'), exist_ok=True)
    json.dump(levers_dict(base), open(os.path.join(ROOT, 'docs', 'kz2025_levers.json'), 'w'), ensure_ascii=False, indent=1)
    json.dump(dict(scale_trln=SCALE, usd_bln_per_model=USD, scenarios={k: dict(title=SCEN[k][0], years=v) for k, v in res.items()}),
              open(os.path.join(ROOT, 'docs', 'kz_vat_results.json'), 'w'), ensure_ascii=False, indent=1, default=float)
    md = report(res, SCEN, SCALE, USD, base)
    open(os.path.join(ROOT, 'docs', 'report_kz_vat.md'), 'w').write(md)
    print(md)


def pct(a, b):
    return f'{100 * (a / b - 1):+.1f} %'


