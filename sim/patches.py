"""Правки «patched»-варианта модели. Эталон (файл СНХМ) не меняется: правки применяются к копии
списка блоков перед компиляцией. Каждая правка — именованная функция со словесным обоснованием."""
from __future__ import annotations
import copy
from dataclasses import dataclass
from typing import Callable

from mdn import Block, NONE

SECTORS = range(1, 14)
GROUP_BASES = [k * 1000 + 800 for k in SECTORS] + [15100, 15200, 15300, 15400, 15500, 16100, 16200, 16300, 16400]
CAP_QUALITY = 5.0        # верхний предел индекса качества жизни группы (в исходном состоянии максимум 3.13)


@dataclass
class Patch:
    name: str
    title: str
    why: str
    apply: Callable[[dict[int, Block], "Baseline"], list[str]]


Baseline = "np.ndarray"   # согласованное исходное состояние эталона (v[idx]); правки нормируются к нему,
                          # чтобы при t = 0 patched-вариант совпадал с файлом, а менялась только динамика


def _group_size_by_employment(by: dict[int, Block], base) -> list[str]:
    log = []
    for k in SECTORS:
        b, i029 = by[k * 1000 + 811], k * 1000 + 29
        assert b.typ == 2 and b.srcs == [k * 1000 + 12], b
        ratio = float(base[k * 1000 + 12]) / float(base[i029])
        b.srcs, b.coefs = [i029], [ratio]
        b.patched = f'численность = {ratio:.4g}·занятые #{i029} (при t=0 равна файловой; было: подано труда #{k}012)'
        log.append(f'#{b.idx}: {b.patched}')
    u = by[15411]
    assert u.typ == 2 and u.srcs == [NONE], u
    u.srcs, u.coefs = [231], [1.0 / float(base[231])]
    u.patched = f'численность безработных = #231/{float(base[231]):.3g} (в единицах файла: 1 при исходной безработице; было: константа 1)'
    log.append(f'#15411: {u.patched}')
    return log


def _cap_quality_index(by: dict[int, Block], base) -> list[str]:
    log = []
    for base in GROUP_BASES:
        b = by[base + 58]
        assert b.typ == 12 and 'качество' in b.name, b
        b.hi = CAP_QUALITY
        b.patched = f'индекс качества жизни ограничен сверху {CAP_QUALITY:g}'
    log.append(f'#k858 (22 группы): верхний предел {CAP_QUALITY:g}')
    return log


# --- инфляция: инерционный процесс поверх модели в постоянных ценах -----------------------------------
# Сама модель считает в постоянных ценах (ставки зарплат, планы бюджета, курс — константы) и устойчивой
# инфляции не порождает; попытки индексировать внутри неё зарплаты/бюджет/курс дают рост выпуска, а не цен
# (зарплаты — 6–10 % издержек, труд эластичен), а движущийся целевой курс разносит валютный контур.
# Поэтому инфляция описана отдельным блоком: дефлятор D растёт с темпом, который складывается из инерции
# (ζ · ожидания), внешнего фона и денежного члена (только при включённой эмиссии); относительные сдвиги
# цен модели (например, от НДС) входят в измеренную инфляцию и через ожидания дают эффект второго круга.
M_RATIO = 0.38          # монетизация M/ВВП (Казахстан 2025: M2/ВВП ≈ 0.35–0.40); рычаг #14002
T_CPI = 1.0             # окно измерения инфляции по ИПЦ модели, лет
T_EXPECT = 1.0          # лаг адаптации инфляционных ожиданий, лет
INDEXATION = 0.5        # ζ — доля прошлой инфляции, переносимая в новую (рычаг #14010); 1 — полная спираль
CPI_WEIGHTS = {4190: 0.40, 5150: 0.30, 5: 0.20, 4: 0.10}   # продовольствие, ТНП, услуги, досуг
DEF_IDX, M_IDX, MON_IDX, D_IDX = 14001, 14002, 14003, 14004
CPI_IDX, PUSH_IDX, ZETA_IDX, CPIL_IDX, PIM_IDX, PIE_IDX, PIA_IDX, DD_IDX = range(14008, 14016)
PIN_IDX, GDPN_IDX, CPIN_IDX, DIDX_IDX, RATIO_IDX = 14016, 14017, 14018, 14019, 14020
INFLATION_BLOCKS = [DEF_IDX, M_IDX, MON_IDX, D_IDX, *range(CPI_IDX, RATIO_IDX + 1)]
T_INDEX = 0.5           # среднее запаздывание индексации бюджетных выплат, лет (индексация раз в год по прошлой инфляции)
SOCIAL_NOMINAL = [114, 115, 116, 117]   # планы выплат бюджетникам, военным, пенсионерам, безработным — в номинале


def _new(idx: int, typ: int, name: str, srcs=(), coefs=(), ra=(), rb=(), pa=(), pb=(), saved=0.0, why='') -> Block:
    b = Block(idx=idx, typ=typ, name=name, a=len(ra), aa=len(rb), n=len(srcs), flag0=0,
              pa=list(pa), ra=list(ra), pb=list(pb), rb=list(rb), coefs=list(coefs), srcs=list(srcs), saved=saved)
    b.patched = why or 'новый блок правки'
    return b


def _inflation(by: dict[int, Block], base) -> list[str]:
    log = []
    for i in INFLATION_BLOCKS:
        assert i not in by, i
    cpi_srcs = list(CPI_WEIGHTS)
    cpi_coefs = [w / float(base[i]) for i, w in CPI_WEIGHTS.items()]      # ИПЦ = 1 при t = 0
    add = [
        _new(DEF_IDX, 1, 'первичный дефицит бюджета (со знаком)', srcs=[51, 42], coefs=[1.0, -1.0],
             why='расходы #51 − доходы #42 (справочно)'),
        _new(M_IDX, 2, 'монетизация M/ВВП', srcs=[NONE], coefs=[1.0], ra=[M_IDX], pa=[M_RATIO],
             why=f'рычаг: денежная масса в долях ВВП ({M_RATIO:g})'),
        _new(MON_IDX, 11, 'денежная инфляция от эмиссии, доли в год', ra=[191], rb=[M_IDX, 155], pa=[0.0], pb=[0.0],
             why='эмиссия #191 / (монетизация · ВВП): деньги сверх спроса на них; 0 при выключенной эмиссии'),
        _new(CPI_IDX, 1, 'ИПЦ модели в постоянных ценах (t = 0 → 1)', srcs=cpi_srcs, coefs=cpi_coefs,
             why='взвешенные розничные цены: продовольствие #4190 0.4, ТНП #5150 0.3, услуги #5 0.2, досуг #4 0.1'),
        _new(PUSH_IDX, 2, 'внешний инфляционный фон, % в год', srcs=[NONE], coefs=[0.01], ra=[PUSH_IDX], pa=[0.0],
             why='рычаг: составляющая инфляции вне модели (импорт, тарифы, сложившиеся ожидания); в файле 0'),
        _new(ZETA_IDX, 2, 'инерционная составляющая ζ·ожидания', srcs=[PIE_IDX], coefs=[1.0], ra=[ZETA_IDX], pa=[INDEXATION],
             why=f'рычаг ζ: доля ожидаемой инфляции, переносимая в новые цены ({INDEXATION:g}; 1 — полная спираль)'),
        _new(CPIL_IDX, 4, 'ИПЦ модели год назад (лаг)', srcs=[CPI_IDX], coefs=[1.0], ra=[0], rb=[0, 0],
             pa=[1.0], pb=[1.0, T_CPI], saved=1.0, why=f'лаг {T_CPI:g} г. от #{CPI_IDX}'),
        _new(PIM_IDX, 13, 'инфляция относительных цен модели, доли в год', srcs=[CPI_IDX, CPIL_IDX], coefs=[1 / T_CPI, -1 / T_CPI],
             rb=[CPIL_IDX], pb=[0.0], why='(ИПЦ − ИПЦ год назад) / ИПЦ год назад — сдвиги цен самой модели (НДС и т. п.)'),
        _new(PIE_IDX, 4, 'инфляционные ожидания, доли в год', srcs=[PIN_IDX], coefs=[1.0], ra=[0], rb=[0, 0],
             pa=[1.0], pb=[1.0, T_EXPECT], saved=0.0, why=f'адаптивные: лаг {T_EXPECT:g} г. от номинальной инфляции #{PIN_IDX}'),
        _new(PIA_IDX, 1, 'инфляция дефлятора, доли в год', srcs=[ZETA_IDX, PUSH_IDX, MON_IDX], coefs=[1.0, 1.0, 1.0],
             why='ζ·ожидания + фон + денежная составляющая'),
        _new(DD_IDX, 9, 'прирост дефлятора', ra=[D_IDX, PIA_IDX], pa=[0.0, 0.0], why='D · инфляция дефлятора'),
        _new(D_IDX, 3, 'дефлятор (t = 0 → 1)', srcs=[DD_IDX], coefs=[1.0], ra=[0], pa=[1.0], saved=1.0,
             why='dD/dt = D · инфляция дефлятора; номинальные показатели = реальные · D'),
        _new(PIN_IDX, 1, 'номинальная инфляция, доли в год', srcs=[PIA_IDX, PIM_IDX], coefs=[1.0, 1.0],
             why='инфляция дефлятора + инфляция относительных цен модели'),
        _new(GDPN_IDX, 9, 'ВВП номинальный', ra=[155, D_IDX], pa=[0.0, 0.0], why='#155 · дефлятор'),
        _new(CPIN_IDX, 9, 'ИПЦ номинальный (t = 0 → 1)', ra=[CPI_IDX, D_IDX], pa=[0.0, 0.0], why=f'#{CPI_IDX} · дефлятор'),
        _new(DIDX_IDX, 4, 'индекс индексации бюджетных выплат (лаг номинального ИПЦ)', srcs=[CPIN_IDX], coefs=[1.0], ra=[0], rb=[0, 0],
             pa=[1.0], pb=[1.0, T_INDEX], saved=1.0, why=f'лаг {T_INDEX:g} г. от номинального ИПЦ #{CPIN_IDX}: выплаты индексируются по прошлой инфляции'),
        _new(RATIO_IDX, 11, 'реальная ценность бюджетных выплат в ценах модели', ra=[DIDX_IDX], rb=[D_IDX], pa=[0.0], pb=[0.0],
             why=f'#{DIDX_IDX}/#{D_IDX}: при устойчивой инфляции π равна 1/(1+π·{T_INDEX:g}); скачок цен модели (НДС) '
                 'сначала съедает выплаты, затем компенсируется индексацией'),
    ]
    for b in add:
        by[b.idx] = b
        log.append(f'#{b.idx} ({b.name}): {b.patched}')
    for i in SOCIAL_NOMINAL:
        b = by[i]
        assert b.typ == 2 and b.srcs == [NONE] and b.coefs == [1.0], b
        b.srcs = [RATIO_IDX]
        b.patched = f'реальная выплата = план · #{RATIO_IDX} (план — в номинале, индексируется с лагом {T_INDEX:g} г.)'
    log.append(f'#114–#117 (бюджетники, военные, пенсионеры, безработные): выплаты · #{RATIO_IDX} — инфляция обесценивает их до индексации')
    return log


